  const DEFAULT = 'en';
  const pick = (lang) => (LANGS.includes(lang) ? lang : DEFAULT);

  // A missing key falls back to English, then to the key itself, so a gap shows up instead of breaking.
  function t(lang, key, vars = {}) {
    const text = STRINGS[pick(lang)][key] ?? STRINGS[DEFAULT][key] ?? key;
    return text.replace(/\{(\w+)\}/g, (m, name) => (vars[name] !== undefined ? String(vars[name]) : m));
  }

